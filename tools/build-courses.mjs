// Validates course lines and writes js/courses/<id>.js (run: node tools/build-courses.mjs)
import { Chess } from '../vendor/chess.js';
import fs from 'node:fs';

const COURSES = [
  { id: 'italian', file: 'italian.txt', title: 'The Italian Game', color: 'white',
    tiers: [['Essentials', 30, 'Most players start here'], ['Advanced', 60, 'For players rated 1400+'], ['Full Mastery', 122, 'For players rated 1800+']] },
  { id: 'caro-kann', file: 'caro-kann.txt', title: 'The Caro-Kann', color: 'black',
    tiers: [['Essentials', 19, 'Most players start here'], ['Full Mastery', 30, 'Every line in the course']] },
  { id: 'alapin', file: 'alapin.txt', title: 'Alapin Sicilian', color: 'white',
    tiers: [['Essentials', 20, 'Most players start here'], ['Full Mastery', 57, 'Every line in the course']] },
  { id: 'scandinavian', file: 'scandinavian.txt', title: 'Counter the Scandinavian', color: 'white',
    tiers: [['Essentials', 12, 'Most players start here'], ['Full Mastery', 38, 'Every line in the course']] },
  { id: 'french', file: 'french.txt', title: 'Counter the French', color: 'white',
    tiers: [['Essentials', 12, 'Most players start here'], ['Full Mastery', 30, 'Every line in the course']] },
  // fixedOrder: the file already lists the Essentials lines first
  { id: 'okelly', file: 'okelly.txt', title: "O'Kelly Sicilian", color: 'black', fixedOrder: true,
    tiers: [['Essentials', 16, 'Most players start here'], ['Full Mastery', 30, 'Every line in the course']] },
  { id: 'kan', file: 'kan.txt', title: 'Sicilian Kan', color: 'black',
    tiers: [['Essentials', 25, 'Most players start here'], ['Full Mastery', 52, 'Every line in the course']] },
];

export function parsePgnMoves(pgn) {
  return pgn.replace(/\{[^}]*\}/g, '').replace(/\d+\.(\.\.)?/g, ' ').replace(/(1-0|0-1|1\/2-1\/2|\*)/g, '')
    .split(/\s+/).filter(Boolean);
}

let allOk = true;
for (const c of COURSES) {
  const raw = fs.readFileSync(`data/${c.file}`, 'utf8').trim().split('\n');
  const lines = raw.map((row, i) => {
    let name = '', pgn = row;
    if (row.includes('|')) [name, pgn] = row.split('|');
    const sans = parsePgnMoves(pgn);
    const ch = new Chess();
    const clean = [];
    for (const s of sans) {
      try { clean.push(ch.move(s).san); } catch (e) { console.error(`${c.id} line ${i + 1}: illegal ${s}`); allOk = false; break; }
    }
    return { name, moves: clean };
  });
  fs.mkdirSync('js/courses', { recursive: true });
  const out = { id: c.id, title: c.title, color: c.color, fixedOrder: !!c.fixedOrder, tiers: c.tiers.map(([name, count, sub]) => ({ name, count, sub })), lines };
  fs.writeFileSync(`js/courses/${c.id}.js`, `// Generated by tools/build-courses.mjs from data/${c.file}\nexport default ${JSON.stringify(out)};\n`);
  // node listing for note writing
  const seen = new Map();
  lines.forEach((l, li) => l.moves.forEach((m, i) => {
    const key = l.moves.slice(0, i + 1).join(' ');
    if (!seen.has(key)) seen.set(key, { ply: i, lines: [] });
    seen.get(key).lines.push(li + 1);
  }));
  const ours = c.color === 'white' ? 0 : 1;
  const parentKids = new Map();
  for (const k of seen.keys()) { const p = k.split(' ').slice(0, -1).join(' '); parentKids.set(p, (parentKids.get(p) || 0) + 1); }
  let txt = '', nOurs = 0, nBranch = 0;
  for (const [k, v] of seen) {
    const mine = v.ply % 2 === ours;
    const p = k.split(' ').slice(0, -1).join(' ');
    const branch = parentKids.get(p) > 1;
    if (mine) nOurs++; if (!mine && branch) nBranch++;
    txt += `${mine ? 'OURS ' : branch ? 'THEIR-BRANCH' : 'THEIRS'}\t${k}\n`;
  }
  console.log(c.id, 'lines', lines.length, 'nodes', seen.size, 'ours', nOurs, 'opp branch', nBranch);
}
if (!allOk) process.exit(1);
